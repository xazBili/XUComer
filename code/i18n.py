def system_lang():
    try:
        lid = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        b1 = ctypes.create_unicode_buffer(16)
        b2 = ctypes.create_unicode_buffer(16)
        ctypes.windll.kernel32.GetLocaleInfoW(lid, 0x59, b1, 16)
        ctypes.windll.kernel32.GetLocaleInfoW(lid, 0x5A, b2, 16)
        full = '%s_%s' % (b1.value, b2.value)
        code = (b1.value or '').lower()
    except Exception:
        full = locale.getdefaultlocale()[0] or ''
        code = full.split('_')[0].lower()
    if full.replace('-', '_') in DATA:
        return full.replace('-', '_')
    if full.replace('-', '_').split('_')[0] in DATA:
        return full.replace('-', '_').split('_')[0]
    if 'zh' in full.lower() and ('TW' in full.upper() or 'HK' in full.upper() or 'MO' in full.upper()):
        return 'zh_TW'
    if 'zh' in full.lower():
        return 'zh_CN'
    for known in DATA:
        if known.lower().split('_')[0] == code:
            return known
    return 'en'


