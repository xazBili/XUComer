def resolve(code):
    if code in (None, '', 'system'):
        return system_lang()
    return code if code in DATA else system_lang()


def t(key, *args):
    if key == 'system':
        return SYSTEM_NAMES.get(LANG, SYSTEM_NAMES['en'])
    for code in [LANG] + FALLBACK:
        s = DATA.get(code, {}).get(key)
        if s is not None:
            return s % args if args else s
    return key
